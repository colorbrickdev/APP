// =============================================================
// 전역 store + listener (React 외부에서도 변경 가능)
// =============================================================
const _i18nStore = {
  lang: 'ko',
  listeners: new Set(),
  setLang(next) {
    if (this.lang === next) return;
    this.lang = next;
    try { localStorage.setItem('atomy_lang', next); } catch {}
    this.listeners.forEach(fn => fn(next));
  },
  subscribe(fn) {
    this.listeners.add(fn);
    return () => this.listeners.delete(fn);
  },
};
// 초기화: localStorage에서 언어 복원
try {
  const saved = localStorage.getItem('atomy_lang');
  if (saved && I18N_DICT[saved]) _i18nStore.lang = saved;
} catch {}

// =============================================================
// translate fn
// =============================================================
function _interpolate(str, vars) {
  if (!vars) return str;
  return String(str).replace(/\{(\w+)\}/g, (_, k) => (vars[k] !== undefined ? vars[k] : `{${k}}`));
}

function translate(key, vars, langOverride) {
  const lang = langOverride || _i18nStore.lang;
  const dict = I18N_DICT[lang] || I18N_DICT.ko;
  const fallback = I18N_DICT.ko;
  const raw = dict[key] !== undefined ? dict[key] : (fallback[key] !== undefined ? fallback[key] : key);
  return _interpolate(raw, vars);
}

// =============================================================
// React hook
// =============================================================
function useTranslation() {
  const [lang, setLangState] = React.useState(_i18nStore.lang);
  React.useEffect(() => {
    return _i18nStore.subscribe(setLangState);
  }, []);
  const t = React.useCallback((key, vars) => translate(key, vars, lang), [lang]);
  const setLang = React.useCallback((next) => _i18nStore.setLang(next), []);
  return { t, lang, setLang };
}

Object.assign(window, {
  I18N_DICT,
  i18nStore: _i18nStore,
  translate,
  useTranslation,
});
